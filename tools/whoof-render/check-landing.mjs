import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
const app=resolve(import.meta.dirname,'../../src');
const markup=readFileSync(resolve(app,'dist/index.html'),'utf8');
const blocks=[...markup.matchAll(/data-block="(\d+)"/g)].map(m=>Number(m[1]));
assert.deepEqual(blocks,[1,2,3,4,5,6,8,9],'superseded Wearing section removed; remaining semantic IDs retained');
assert.equal((markup.match(/<h1\b/g)||[]).length,1);
for(const id of ['wearing','details','life'])assert.ok(!markup.includes(`id="${id}"`),id+' legacy screen is not rendered');
assert.ok(!markup.includes('class="life-card"')&&!markup.includes('data-step='),'old gallery and spec controls removed');
assert.equal((markup.match(/data-story-row/g)||[]).length,5,'complete second block includes all five informative lower rows');
assert.ok(markup.includes('id="situations-table"'),'second block is more than its introductory viewport');
assert.ok(!markup.includes('hero-app-preview')&&!markup.includes('hero-preorder'),'preserve requested hero removals');
assert.ok(markup.indexOf('id="order"')>markup.indexOf('id="trust"'),'Trust now leads directly to Offer');
for(const [,hash] of markup.matchAll(/href="#([^"]+)"/g))assert.ok(markup.includes(`id="${hash}"`),'internal anchor '+hash+' resolves');
assert.ok(!markup.includes('app-profile.webp'),'do not reintroduce unsupported pulse mockup');
assert.ok(markup.includes('14 990')&&markup.includes('19 990')&&markup.includes('6 000'));
assert.ok(markup.includes('предзаказ')&&markup.includes('Bluetooth'));
assert.ok(!markup.includes('life-prev')&&!markup.includes('life-dots'));
assert.ok(existsSync(resolve(app,'../../saved-versions/whoof-v26-2026-10-27/site/index.html')),'independent v26 build exists');
for(const [,path] of markup.matchAll(/(?:src|poster)="(\/whoof\/[^"?#]+)"/g))assert.ok(existsSync(resolve(app,'public'+path)),path+' exists');
console.log('Landing: eight remaining sections, removed legacy screens/controls, valid anchors, saved baseline, source facts and asset paths passed.');
